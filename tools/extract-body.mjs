import { createRequire } from 'module';
import { writeFileSync } from 'fs';
const require = createRequire(import.meta.url);
const dir = process.argv[2];
const load = (f) => require(`${dir}/${f}.js`);
const pack = (list) => list.map((m) => ({ slug: m.slug, d: [...(m.path.left || []), ...(m.path.right || []), ...(m.path.common || [])] }));
const data = {
  male: { front: pack(load('bodyFront').bodyFront), back: pack(load('bodyBack').bodyBack), vb: { front: '0 0 724 1448', back: '724 0 724 1448' } },
  female: { front: pack(load('bodyFemaleFront').bodyFemaleFront), back: pack(load('bodyFemaleBack').bodyFemaleBack), vb: { front: '-50 -40 734 1538', back: '756 0 774 1448' } },
};
writeFileSync('src/data/bodymap.js', `// Body outlines from react-native-body-highlighter (MIT License, Copyright (c) 2022 ELABBASSI Hicham).
// Generated by tools/extract-body.mjs. See THIRD_PARTY_NOTICES.md.
export const BODY = ${JSON.stringify(data)};
`);
console.log('ok', Object.values(data).map((s) => s.front.length + s.back.length));

"""Download exercise photos and instructions from free-exercise-db (Unlicense) for the
exercises listed in preview-map.json, resize them, and write:
  public/ex/<id>-0.jpg, <id>-1.jpg   start and end positions (max 480px wide)
  public/ex/<id>-t.jpg               thumbnail (144px wide)
  public/ex/guide.json               {id: [instruction steps]}
  src/data/previews.js               ids that have a preview
Usage: python3 tools/fetch-previews.py <dataset exercises.json> <download dir>
"""
import io, json, os, sys, urllib.request
from PIL import Image

RAW = 'https://raw.githubusercontent.com/yuhonas/free-exercise-db/main/exercises/'
here = os.path.dirname(os.path.abspath(__file__))
root = os.path.dirname(here)
data = {e['id']: e for e in json.load(open(sys.argv[1]))}
cache = sys.argv[2]
mapping = json.load(open(os.path.join(here, 'preview-map.json')))
out = os.path.join(root, 'public', 'ex')
os.makedirs(out, exist_ok=True)
os.makedirs(cache, exist_ok=True)

def fetch(path):
    local = os.path.join(cache, path.replace('/', '__'))
    if not os.path.exists(local):
        with urllib.request.urlopen(RAW + path, timeout=30) as r:
            open(local, 'wb').write(r.read())
    return Image.open(local).convert('RGB')

guide, ok, missing = {}, [], []
for ours, theirs in mapping.items():
    e = data.get(theirs)
    if not e or len(e['images']) < 2:
        missing.append((ours, theirs)); continue
    frames = [fetch(p) for p in e['images'][:2]]
    for i, im in enumerate(frames):
        w = min(480, im.width)
        im.resize((w, round(im.height * w / im.width)), Image.LANCZOS).save(os.path.join(out, f'{ours}-{i}.jpg'), quality=74, optimize=True, progressive=True)
    im = frames[0]
    tw = 144
    im.resize((tw, round(im.height * tw / im.width)), Image.LANCZOS).save(os.path.join(out, f'{ours}-t.jpg'), quality=72, optimize=True)
    guide[ours] = [s.strip() for s in e['instructions'] if s.strip()]
    ok.append(ours)

json.dump(guide, open(os.path.join(out, 'guide.json'), 'w'), separators=(',', ':'))
with open(os.path.join(root, 'src', 'data', 'previews.js'), 'w') as f:
    f.write('// Generated by tools/fetch-previews.py: exercises with photos from free-exercise-db (Unlicense)\n')
    f.write('export const PREVIEW_IDS = new Set(' + json.dumps(sorted(ok)) + ');\n')
print(f'{len(ok)} previews, missing: {missing}')
